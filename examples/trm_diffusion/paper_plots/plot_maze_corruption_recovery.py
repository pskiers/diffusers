"""Maze corruption-recovery: does PaTh/DM notice and fix its own mistakes?

Three corruption modes, each injected at some point in the sampling
schedule and then denoised for the remaining steps. The CSV's `t_start`
column is a diffusion-timestep-like quantity that runs from large (start
of sampling) down to 0 (end of sampling) -- i.e. it counts DOWN as
sampling proceeds. So "t_start=90" means the mistake is injected very
early (only ~10% of the schedule has run), and "t_start=10" means it's
injected very late (~90% of the schedule has already run, very little
denoising budget left to fix it). Displayed axis labels use the more
intuitive "% of sampling completed when injected" = 100 - t_start (same
convention/label text as the sudoku plot's PCT), so what's displayed as
"10%" pulls the t_start=90 rows and what's displayed as "90%" pulls the
t_start=10 rows.

The three modes:

  - wall: the path is redrawn straight through a wall pixel. A violation
    is checkable by looking at a single pixel (the path/wall overlap) --
    LOCALLY checkable.
  - gap: the path is simply cut short -- correct up to the injection
    point, then nothing. The drawn path's endpoint sits in the middle of an open
    corridor instead of terminating at a wall/dead end/goal -- an
    unfinished stroke that is visible by looking at the immediate
    neighbourhood of the endpoint alone. LOCALLY checkable.
  - add: the path takes a wrong turn into a dead end and walks all the
    way to the end of it. Locally the stroke looks exactly like a
    *valid, completed* path (it terminates cleanly against walls on
    three sides, same as a real goal cell would) -- telling it apart
    from a correct solution requires checking, elsewhere in the image,
    where the real goal is and whether this endpoint matches it.
    GLOBALLY checkable.

So the local/global pair of interest is gap (local) vs. add (global);
wall is a third, separately locally-checkable reference point.

Data source: examples/trm_diffusion/paper_plots/maze_corruption_recovery_summary.csv
(user-provided aggregate; not regenerated by a script in this repo) for the
heatmaps and tables. The four avg_over_levels bar charts use a SEPARATE,
smaller transcription (LG_DATA below) of add/gap "erased"/"redrawn" rates
the user supplied from their own reference heatmaps -- those numbers don't
match any column/formula derivable from the summary CSV (checked
recovery_rate, erased_rate=1-adapt_rate, denoised_coverage, ceiling_coverage,
remaining_gt_recall -- none reproduce them), so per the user this is
probably a different underlying run, and LG_DATA is treated as authoritative
for just those four figures instead. LG_DATA is stored by raw t_start, but
all four figures display it relabeled as "% of sampling completed when
injected" = 100 - t_start, same convention as the CSV-derived heatmaps.

Produces (mirrors paper_plots/plot_sudoku_violation_sensitivity.py):
  - maze_corruption_recovery_heatmaps_{mode}.pdf (mode in wall/add/gap):
    PaTh vs. DM heatmaps. Rows = t_start ("Mistake simulated at % of
    sampling", same label/position as the sudoku plot), columns = maze
    difficulty level (replaces "number of corrupted cells"). Cell metric
    is full_recovery_rate for wall; recovery_rate -- the per-cell fraction
    of the erased/never-drawn cells redrawn back to the ground truth
    ("erased cells redrawn") -- for gap; and erased_rate = 1 - adapt_rate
    -- the fraction of wrong dead-end/shortcut pixels no longer present in
    the output ("shortcut pixels erased") -- for add.
  - maze_corruption_recovery_local_global_diff_heatmaps.pdf: PaTh vs. DM
    heatmaps of gap's recovery_rate - add's erased_rate -- local-mistake
    fix rate minus global-mistake fix rate, within each model. Rows =
    t_start; columns = difficulty rank (add's 3 levels against gap's 3
    easiest, aligned easiest-to-hardest since the two modes don't share
    raw level values).
  - maze_corruption_recovery_avg_over_levels_{add,gap}.pdf: LG_DATA's
    "erased"/"redrawn" rate averaged over difficulty level, PaTh vs. DM
    grouped bars vs. % of sampling completed.
  - maze_corruption_recovery_avg_over_levels_add_gap_combined.pdf: same,
    additionally averaged across mistake type (add and gap weighted
    equally, each already averaged over its own levels).
  - maze_corruption_recovery_avg_over_levels_local_global_diff.pdf: local
    (gap) - global (add), differenced level-by-level at matched hardness
    rank then averaged -- PaTh vs. DM grouped bars vs. % of sampling
    completed (a 0 pp diff draws no bar).
  - maze_corruption_recovery_tables.tex: 6 LaTeX tables (3 modes x
    {full_recovery_rate, recovery_rate}), rows = difficulty level, columns
    = t_start x {PaTh, DM}.

Usage:
    python paper_plots/plot_maze_corruption_recovery.py
"""
import numpy as np
import pandas as pd

import matplotlib
import matplotlib.pyplot as plt

matplotlib.rcParams.update({
    "font.family": "serif",
    "font.serif": ["Times New Roman", "Times", "DejaVu Serif"],
    "mathtext.fontset": "stix",
    "font.size": 11,
    "axes.labelsize": 12,
    "axes.titlesize": 12,
    "xtick.labelsize": 10,
    "ytick.labelsize": 10,
    "legend.fontsize": 10,
    "axes.linewidth": 1.0,
    "pdf.fonttype": 42,
    "ps.fonttype": 42,
})

COLOR_DM = "#2c2c2a"
COLOR_THINKER = "#8b3fd9"
MODEL_LABEL = {"trm": "PaTh", "dit": "DM"}
MODEL_COLOR = {"trm": COLOR_THINKER, "dit": COLOR_DM}

MODE_TITLE = {"wall": "Wall crossing", "add": "Dead-end detour (global)", "gap": "Cut-short path (local)"}
MODES = ["wall", "add", "gap"]

# wall: full_recovery_rate (no longer crosses the wall at all).
# gap: recovery_rate -- the per-cell fraction of the erased/never-drawn
# cells that got correctly redrawn back to the ground-truth path
# ("erased cells redrawn").
# add: erased_rate = 1 - adapt_rate -- the fraction of the wrong
# dead-end/shortcut pixels that are no longer reproduced in the output
# ("shortcut pixels erased"). This is a looser bar than recovery_rate: it
# only asks whether the wrong shortcut got removed, not whether what
# replaced it is an exact ground-truth match.
HEATMAP_METRIC = {"wall": "full_recovery_rate", "add": "erased_rate", "gap": "recovery_rate"}

T_START = [10, 30, 50, 70, 90]  # display labels: % of sampling completed when injected (ascending)
LEVELS = {"wall": [10, 30, 50, 75], "gap": [30, 50, 75], "add": [0, 20, 50]}

DATA_CSV = "paper_plots/maze_corruption_recovery_summary.csv"

# ── Reference data for the 4 avg_over_levels figures ────────────────────────
# Transcribed from the user's own reference heatmaps (not derivable from
# DATA_CSV -- see module docstring). Rows = level (ascending, matches
# LG_LEVELS[mode]), columns = raw t_start = LG_T_START (mistake injected at
# this raw diffusion-timestep-like value; ascending left-to-right, i.e. NOT
# the "100 - t_start" relabeling used by the CSV-derived heatmaps above).
LG_T_START = [10, 30, 50, 70, 90]
LG_LEVELS = {"gap": [10, 30, 50, 75], "add": [0, 20, 50]}
LG_DATA = {
    "gap": {  # "erased cells redrawn"
        "trm": [
            [0.12, 0.23, 0.87, 1.00, 1.00],
            [0.03, 0.04, 0.56, 1.00, 1.00],
            [0.02, 0.04, 0.52, 0.99, 1.00],
            [0.03, 0.06, 0.60, 0.99, 1.00],
        ],
        "dit": [
            [0.23, 0.24, 0.56, 0.92, 0.96],
            [0.08, 0.09, 0.25, 0.79, 0.93],
            [0.06, 0.07, 0.31, 0.83, 0.93],
            [0.05, 0.09, 0.51, 0.86, 0.93],
        ],
    },
    "add": {  # "wrong cells erased"
        "trm": [
            [0.04, 0.16, 0.62, 1.00, 1.00],
            [0.06, 0.20, 0.77, 1.00, 1.00],
            [0.07, 0.17, 0.71, 1.00, 1.00],
        ],
        "dit": [
            [0.08, 0.15, 0.37, 0.63, 0.77],
            [0.13, 0.23, 0.47, 0.66, 0.84],
            [0.19, 0.28, 0.43, 0.61, 0.74],
        ],
    },
}


def _lg_matrix(mode, model):
    """(len(LG_T_START), len(LG_LEVELS[mode])) matrix: rows = t_start,
    columns = level (transcribed as level x t_start, so transpose)."""
    return np.array(LG_DATA[mode][model]).T


def load():
    df = pd.read_csv(DATA_CSV)
    df["erased_rate"] = 1 - df["adapt_rate"]
    return df


def _raw_t(pct):
    """Displayed '% of sampling completed' label -> raw CSV t_start value.
    t_start counts down as sampling proceeds, so completed% = 100 - t_start."""
    return 100 - pct


def _matrix(df, mode, model, metric):
    """(len(T_START), len(levels)) matrix: rows = % of sampling completed
    when injected (display label, ascending), columns = level."""
    levels = LEVELS[mode]
    sub = df[(df["mode"] == mode) & (df["model"] == model)]
    mat = np.zeros((len(T_START), len(levels)))
    for i, pct in enumerate(T_START):
        t = _raw_t(pct)
        for j, lv in enumerate(levels):
            row = sub[(sub["level"] == lv) & (sub["t_start"] == t)]
            mat[i, j] = row[metric].iloc[0]
    return mat


# ── Per-mode heatmaps: PaTh vs. DM, rows = t_start, columns = level ────────


def _draw_heatmap_pair(axes, th_mat, dm_mat, levels, cmap, vmin, vmax, fmt, vabs_center=None):
    for ax, mat, title, color in [
        (axes[0], th_mat, "PaTh", COLOR_THINKER),
        (axes[1], dm_mat, "DM", COLOR_DM),
    ]:
        ax.imshow(mat, cmap=cmap, vmin=vmin, vmax=vmax, aspect="auto")
        ax.set_xticks(range(len(levels)))
        ax.set_xticklabels([str(lv) for lv in levels])
        ax.set_xlabel("Maze difficulty level")
        ax.set_title(title, color=color, fontweight="bold")
        for spine in ax.spines.values():
            spine.set_visible(False)
        thresh = vabs_center if vabs_center is not None else 0.55 * (vmax - vmin) + vmin
        for i in range(mat.shape[0]):
            for j in range(mat.shape[1]):
                v = mat[i, j]
                if vabs_center is not None:
                    light = abs(v - vabs_center) > 0.6 * (vmax - vabs_center)
                else:
                    light = v < thresh
                text_color = "white" if light else "black"
                ax.text(j, i, fmt(v), ha="center", va="center", fontsize=8.5, color=text_color)

    axes[0].set_yticks(range(len(T_START)))
    axes[0].set_yticklabels([f"{p}%" for p in T_START])
    axes[0].set_ylabel("Mistake simulated at % of sampling")


def make_mode_heatmap(mode):
    df = load()
    levels = LEVELS[mode]
    metric = HEATMAP_METRIC[mode]
    th_mat = _matrix(df, mode, "trm", metric) * 100
    dm_mat = _matrix(df, mode, "dit", metric) * 100
    vmax = max(th_mat.max(), dm_mat.max())

    fig, axes = plt.subplots(1, 2, figsize=(6.4, 2.9), sharey=True)
    _draw_heatmap_pair(axes, th_mat, dm_mat, levels, plt.get_cmap("viridis"), 0.0, vmax, lambda v: f"{v:.1f}")
    fig.suptitle(MODE_TITLE[mode], y=1.04)

    fname = f"paper_plots/maze_corruption_recovery_heatmaps_{mode}.pdf"
    fig.savefig(fname, bbox_inches="tight")
    print(f"Wrote {fname}")


# ── Local (gap) - global (add) diff heatmaps, per model ────────────────────
#
# gap's mistake is visible by looking only at the drawn path's endpoint
# (an unfinished stroke) -- LOCALLY checkable. add's mistake is a
# structurally valid-looking dead end that is only wrong once you check,
# elsewhere in the image, where the true goal actually is -- GLOBALLY
# checkable. A model that is truly using local cues but not solving the
# maze end-to-end should recover gap much more often than add: a large
# positive diff here is exactly that signature.
#
# add has 3 difficulty levels ([0, 20, 50]) and gap has 3 ([30, 50, 75])
# -- they don't share raw values, so we align the two axes by hardness
# RANK (easiest, ..., hardest) instead.


def make_local_global_diff_heatmap():
    df = load()
    n = len(LEVELS["add"])  # 3 -- the shorter of the two level axes
    gap_metric, add_metric = HEATMAP_METRIC["gap"], HEATMAP_METRIC["add"]
    gap_th = _matrix(df, "gap", "trm", gap_metric)[:, :n]
    gap_dm = _matrix(df, "gap", "dit", gap_metric)[:, :n]
    add_th = _matrix(df, "add", "trm", add_metric)
    add_dm = _matrix(df, "add", "dit", add_metric)

    th_diff = (gap_th - add_th) * 100
    dm_diff = (gap_dm - add_dm) * 100
    vabs = max(np.abs(th_diff).max(), np.abs(dm_diff).max())

    fig, axes = plt.subplots(1, 2, figsize=(6.4, 2.9), sharey=True)
    ranks = [f"{i + 1}" for i in range(n)]
    _draw_heatmap_pair(axes, th_diff, dm_diff, ranks, plt.get_cmap("RdBu_r"), -vabs, vabs,
                        lambda v: f"{v:+.1f}", vabs_center=0.0)
    axes[0].set_xlabel("Maze hardness rank (1 = easiest)")
    axes[1].set_xlabel("Maze hardness rank (1 = easiest)")

    fname = "paper_plots/maze_corruption_recovery_local_global_diff_heatmaps.pdf"
    fig.savefig(fname, bbox_inches="tight")
    print(f"Wrote {fname}")


# ── Bar-chart views: one averaged-over-levels bar per model per % bucket ───


def _pct_labels():
    """Ascending "% of sampling completed when injected" labels, matching
    the CSV-derived heatmaps' 100 - raw_t_start convention."""
    return [100 - t for t in reversed(LG_T_START)]


def _bar_axes(ax, pct, ylabel):
    ax.set_xticks(np.arange(len(pct)))
    ax.set_xticklabels([f"{p}%" for p in pct])
    ax.set_xlabel("Mistake simulated at % of sampling")
    ax.set_ylabel(ylabel)
    for spine in ("top", "right"):
        ax.spines[spine].set_visible(False)
    ax.grid(axis="y", color="0.88", lw=0.6, zorder=0)


def _grouped_bars(ax, x, values_by_model, width=0.36):
    """values_by_model: {"trm": array, "dit": array}, each already in
    pct-ascending order. Draws one bar per model per x position."""
    offset = {"trm": -width / 2, "dit": width / 2}
    for model in ["trm", "dit"]:
        ax.bar(x + offset[model], values_by_model[model], width,
               color=MODEL_COLOR[model], label=MODEL_LABEL[model], zorder=3)


def make_avg_over_levels_figure(mode):
    """Plots 1 & 2: LG_DATA[mode] averaged over levels, PaTh vs. DM, one bar
    per model per % of sampling completed."""
    pct = _pct_labels()
    x = np.arange(len(pct))
    fig, ax = plt.subplots(figsize=(4.6, 3.3))
    values = {model: _lg_matrix(mode, model).mean(axis=1)[::-1] * 100 for model in ["trm", "dit"]}
    _grouped_bars(ax, x, values)
    ax.set_ylim(0, 103)
    _bar_axes(ax, pct, "Mistake corrected (\\%)")
    ax.legend(frameon=False, loc="upper right")
    fig.tight_layout()
    fname = f"paper_plots/maze_corruption_recovery_avg_over_levels_{mode}.pdf"
    fig.savefig(fname, bbox_inches="tight")
    print(f"Wrote {fname}")


def make_avg_over_levels_and_mode_figure():
    """Plot 3: same as 1 & 2, but also averaged across mistake type (add and
    gap given equal weight, each already averaged over its own levels)."""
    pct = _pct_labels()
    x = np.arange(len(pct))
    fig, ax = plt.subplots(figsize=(4.6, 3.3))
    values = {}
    for model in ["trm", "dit"]:
        add_avg = _lg_matrix("add", model).mean(axis=1)
        gap_avg = _lg_matrix("gap", model).mean(axis=1)
        values[model] = ((add_avg + gap_avg) / 2)[::-1] * 100
    _grouped_bars(ax, x, values)
    ax.set_ylim(0, 103)
    _bar_axes(ax, pct, "Mistake corrected (\\%)")
    ax.legend(frameon=False, loc="upper right")
    fig.tight_layout()
    fname = "paper_plots/maze_corruption_recovery_avg_over_levels_add_gap_combined.pdf"
    fig.savefig(fname, bbox_inches="tight")
    print(f"Wrote {fname}")


def make_avg_local_global_diff_figure():
    """Plot 4: local (gap) - global (add), differenced level-by-level at
    matched hardness RANK (add has 3 levels, gap has 4 -- use gap's 3
    easiest) and averaged over ranks -- PaTh vs. DM, as a bar chart (a 0 pp
    diff draws no bar) against "% of sampling completed when injected" =
    100 - raw t_start (same convention as the CSV-derived heatmaps)."""
    n = len(LG_LEVELS["add"])  # 3 -- the shorter of the two level axes
    pct = _pct_labels()
    x = np.arange(len(pct))

    fig, ax = plt.subplots(figsize=(4.6, 3.3))
    values = {}
    for model in ["trm", "dit"]:
        add_mat = _lg_matrix("add", model)
        gap_mat = _lg_matrix("gap", model)[:, :n]
        values[model] = (gap_mat - add_mat).mean(axis=1)[::-1] * 100
    _grouped_bars(ax, x, values)

    ax.axhline(0.0, color="0.4", lw=1.0, zorder=2)
    _bar_axes(ax, pct, "Mistake correction difference")
    ax.legend(frameon=False, loc="upper right")
    fig.tight_layout()
    fname = "paper_plots/maze_corruption_recovery_avg_over_levels_local_global_diff.pdf"
    fig.savefig(fname, bbox_inches="tight")
    print(f"Wrote {fname}")


# ── LaTeX tables ─────────────────────────────────────────────────────────


def _fmt(v):
    return f"{100 * v:.1f}"


def _table(th_mat, dm_mat, levels, caption, label):
    """th_mat/dm_mat here are (levels x t_start) -- table rows = level."""
    ncol = len(T_START)
    lines = [
        r"\begin{table}[t]",
        r"\centering",
        r"\resizebox{\textwidth}{!}{",
        r"\begin{tabular}{c" + "c" * ncol * 2 + "}",
        r"\toprule",
        r" & \multicolumn{%d}{c}{PaTh} & \multicolumn{%d}{c}{DM} \\" % (ncol, ncol),
        rf"\cmidrule(lr){{2-{1 + ncol}}} \cmidrule(lr){{{2 + ncol}-{1 + 2 * ncol}}}",
    ]
    header = [r"Level"] + [f"{t}\\%" for t in T_START] * 2
    lines.append(" & ".join(header) + r" \\")
    lines.append(r"\midrule")
    for i, lv in enumerate(levels):
        row = [str(lv)] + [_fmt(v) for v in th_mat[i]] + [_fmt(v) for v in dm_mat[i]]
        lines.append(" & ".join(row) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}}")
    lines.append(rf"\caption{{{caption}}}")
    lines.append(rf"\label{{tab:{label}}}")
    lines.append(r"\end{table}")
    return "\n".join(lines)


def make_tables():
    df = load()
    tables = []
    for metric, metric_label in [
        ("full_recovery_rate", "Full-recovery rate"),
        ("recovery_rate", "Recovery rate (partial credit)"),
    ]:
        for mode in MODES:
            # tables are indexed rows=level, so transpose the (t_start x level) matrix back
            th_mat = _matrix(df, mode, "trm", metric).T
            dm_mat = _matrix(df, mode, "dit", metric).T
            caption = (
                f"{metric_label} (\\%) on the \\emph{{{mode}}} corruption "
                f"({MODE_TITLE[mode].lower()}), as a function of difficulty level and "
                "\\% of sampling completed when the mistake is injected."
            )
            label = f"maze_{metric}_{mode}"
            tables.append(_table(th_mat, dm_mat, LEVELS[mode], caption, label))
    out = "\n\n".join(tables) + "\n"
    with open("paper_plots/maze_corruption_recovery_tables.tex", "w") as f:
        f.write(out)
    print("Wrote paper_plots/maze_corruption_recovery_tables.tex")
    print("\n" + out)


def main():
    for mode in MODES:
        make_mode_heatmap(mode)
    make_local_global_diff_heatmap()
    make_avg_over_levels_figure("add")
    make_avg_over_levels_figure("gap")
    make_avg_over_levels_and_mode_figure()
    make_avg_local_global_diff_figure()
    make_tables()


if __name__ == "__main__":
    main()
